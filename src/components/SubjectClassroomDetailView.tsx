import {
  ArrowLeft,
  BookOpen,
  ChevronDown,
  ChevronUp,
  ExternalLink,
  FileText,
  FilePlus,
  FolderOpen,
  GraduationCap,
  Layers,
  Pencil,
  Play,
  Plus,
  Trash2,
  User,
  Users,
  Video,
  CheckCircle2,
  Clock,
  Target,
  X,
  Save,
  Copy,
} from 'lucide-react';
import {
  Assignment,
  LearningResource,
  StudentProfile,
  SubjectClassroom,
  Submission,
  UserRole,
} from '../types';
import { AssignmentCard } from './AssignmentCard';
