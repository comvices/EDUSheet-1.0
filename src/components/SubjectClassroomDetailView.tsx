import { HeroSvgOrnaments, CardCornerOrnament } from './ThemeGraphics';

interface SubjectClassroomDetailViewProps {
  classroom: SubjectClassroom;
  role: UserRole;
  currentStudentCode?: string;
  studentGradeLevel?: string;
  assignments: Assignment[];
  submissions: Submission[];
  resources: LearningResource[];
  students: StudentProfile[];
  onBack: () => void;
  onEditClassroom: (classroom: SubjectClassroom) => void;
  onCloneClassroom?: (classroom: SubjectClassroom) => void;
  onDeleteClassroom: (classroomId: string) => void;
  onPersistAutoClassroom?: (classroom: SubjectClassroom) => void;
  onOpenSubmitModal: (assignment: Assignment) => void;
  onOpenGradingModal: (assignment: Assignment, submission?: Submission) => void;
  onOpenHintModal: (assignment: Assignment) => void;
  onOpenRosterModal?: (assignment: Assignment) => void;
  onDeleteAssignment?: (assignmentId: string) => void;
  onEditAssignment?: (assignment: Assignment) => void;
  onCloneAssignment?: (assignment: Assignment) => void;
  onOpenCreateWorksheet?: (defaults: { subject: string; gradeLevel: string }) => void;
}

function getYouTubeEmbedUrl(url: string): string | null {
  try {
    const regExp = /^.*(youtu.be\/|v\/|u\/\w\/|embed\/|watch\?v=|\&v=)([^#\&\?]*).*/;
    const match = url.match(regExp);
    if (match && match[2].length === 11) {
      return `https://www.youtube.com/embed/${match[2]}?autoplay=1`;
    }
  } catch {}
  return null;
}

function matchesRoom(classroomGrade: string, targetGrade: string): boolean {
  if (!classroomGrade || classroomGrade === 'ทั้งหมด') return true;
  if (!targetGrade || targetGrade === 'ทั้งหมด') return true;
  if (classroomGrade === targetGrade) return true;
  const baseClass = classroomGrade.includes('/') ? classroomGrade.split('/')[0] : classroomGrade;
  const baseTarget = targetGrade.includes('/') ? targetGrade.split('/')[0] : targetGrade;
  if (!classroomGrade.includes('/') && baseTarget === baseClass) return true;
  if (!targetGrade.includes('/') && baseClass === baseTarget) return true;
  return false;
}

export const SubjectClassroomDetailView: React.FC<SubjectClassroomDetailViewProps> = ({
  classroom,
  role,
  currentStudentCode,
  studentGradeLevel,
  assignments,
  submissions,
  resources,
  students,
  onBack,
  onEditClassroom,
  onCloneClassroom,
  onDeleteClassroom,
  onPersistAutoClassroom,
  onOpenSubmitModal,
  onOpenGradingModal,
  onOpenHintModal,
  onOpenRosterModal,
  onDeleteAssignment,
  onEditAssignment,
  onCloneAssignment,
  onOpenCreateWorksheet,
}) => {
  const isAutoGenerated = classroom.id.startsWith('auto_cls_');
  const [innerTab, setInnerTab] = useState<'units' | 'worksheets' | 'members'>('units');
  const [expandedUnitIds, setExpandedUnitIds] = useState<Record<string, boolean>>(() => {
    const initial: Record<string, boolean> = {};
    if (classroom.units[0]) initial[classroom.units[0].id] = true;
    return initial;
  });
  const [activeVideo, setActiveVideo] = useState<{ url: string; title: string } | null>(null);
  const [confirmDeleteOpen, setConfirmDeleteOpen] = useState(false);

  const sortedUnits = useMemo(
    () => [...(classroom.units || [])].sort((a, b) => a.order - b.order),
    [classroom.units]
  );

  // Subject worksheets matching this classroom's subject & grade scope
  const subjectAssignments = useMemo(() => {
    return assignments.filter(
      (a) => a.subject === classroom.subject && matchesRoom(classroom.gradeLevel, a.gradeLevel)
    );
  }, [assignments, classroom.subject, classroom.gradeLevel]);

  // Subject resources matching this classroom's subject & grade scope
  const subjectResources = useMemo(() => {
    return resources.filter(
      (r) => r.subject === classroom.subject && matchesRoom(classroom.gradeLevel, r.gradeLevel)
    );
  }, [resources, classroom.subject, classroom.gradeLevel]);

  // Classmates / roster matching this classroom's gradeLevel (and student's own room if student role)
  const roomStudents = useMemo(() => {
    return students
      .filter((s) => {
        if (!matchesRoom(classroom.gradeLevel, s.gradeLevel)) return false;
        if (role === 'student' && studentGradeLevel) {
          return matchesRoom(studentGradeLevel, s.gradeLevel);
        }
        return true;
      })
      .sort((a, b) => a.code.localeCompare(b.code, 'th', { numeric: true }));
  }, [students, classroom.gradeLevel, role, studentGradeLevel]);

  // Linked assignments across all units (deduplicated) + subject worksheets for student progress
  const trackedAssignments = useMemo(() => {
    const linkedIds = new Set<string>();
    sortedUnits.forEach((u) => (u.linkedAssignmentIds || []).forEach((id) => linkedIds.add(id)));
    if (linkedIds.size > 0) {
      return assignments.filter((a) => linkedIds.has(a.id));
    }
    return subjectAssignments;
  }, [sortedUnits, assignments, subjectAssignments]);

  const studentProgress = useMemo(() => {
    if (trackedAssignments.length === 0) return { completed: 0, total: 0, pct: 0 };
    let completed = 0;
    trackedAssignments.forEach((asg) => {
      const sub = submissions.find(
        (s) =>
          s.assignmentId === asg.id &&
          (!currentStudentCode || s.studentCode === currentStudentCode)
      );
      if (sub && (sub.status === 'submitted' || sub.status === 'graded')) {
        completed += 1;
      }
    });
    return {
      completed,
      total: trackedAssignments.length,
      pct: Math.round((completed / trackedAssignments.length) * 100),
    };
  }, [trackedAssignments, submissions, currentStudentCode]);

  const safeCover = sanitizeImageSrc(classroom.coverUrl);

  const toggleUnit = (unitId: string) => {
    setExpandedUnitIds((prev) => ({ ...prev, [unitId]: !prev[unitId] }));
  };

  return (
    <div className="space-y-6">
      {/* Top Bar Back & Teacher Actions */}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <button
          type="button"
          onClick={onBack}
          className="inline-flex items-center gap-2 px-3.5 py-2 bg-white dark:bg-[var(--theme-surface-dark)] border border-slate-200 dark:border-emerald-950/70 hover:border-emerald-400 text-slate-700 dark:text-slate-200 rounded-xl text-xs font-semibold transition-colors cursor-pointer"
        >
          <ArrowLeft className="w-4 h-4 text-emerald-700 dark:text-emerald-400" />
          <span>กลับหน้ารายวิชาทั้งหมด</span>
        </button>

        {role === 'teacher' && (
          <div className="flex flex-wrap items-center gap-2">
            {isAutoGenerated && onPersistAutoClassroom && (
              <button
                type="button"
                onClick={() => onPersistAutoClassroom(classroom)}
                className="theme-btn-sheen inline-flex items-center gap-1.5 px-3.5 py-2 bg-teal-700 hover:bg-teal-800 text-white rounded-xl text-xs font-bold shadow-xs transition-colors cursor-pointer"
              >
                <Save className="w-3.5 h-3.5" />
                <span>บันทึกห้องเรียนนี้ลงระบบ</span>
              </button>
            )}
            {onCloneClassroom && (
              <button
                type="button"
                onClick={() => onCloneClassroom(classroom)}
                className="inline-flex items-center gap-1.5 px-3.5 py-2 bg-white dark:bg-[var(--theme-surface-dark)] border border-emerald-200 dark:border-emerald-800/70 hover:border-teal-400 text-teal-700 dark:text-teal-300 rounded-xl text-xs font-bold shadow-2xs transition-colors cursor-pointer"
              >
                <Copy className="w-3.5 h-3.5" />
                <span>คัดลอกห้องเรียนไปห้องอื่น</span>
              </button>
            )}
            <button
              type="button"
              onClick={() => onEditClassroom(classroom)}
              className="theme-btn-sheen inline-flex items-center gap-1.5 px-3.5 py-2 bg-emerald-700 hover:bg-emerald-800 text-white rounded-xl text-xs font-bold shadow-xs transition-colors cursor-pointer"
            >
              <Pencil className="w-3.5 h-3.5" />
              <span>{isAutoGenerated ? 'ปรับแต่งและบันทึก' : 'แก้ไขห้องเรียน / เพิ่มบทเรียน'}</span>
            </button>
            {!isAutoGenerated && (
              <button
                type="button"
                onClick={() => setConfirmDeleteOpen(true)}
                className="inline-flex items-center gap-1.5 px-3.5 py-2 bg-white dark:bg-[var(--theme-surface-dark)] border border-slate-200 dark:border-emerald-950/70 hover:border-rose-300 text-rose-600 dark:text-rose-400 rounded-xl text-xs font-semibold transition-colors cursor-pointer"
              >
                <Trash2 className="w-3.5 h-3.5" />
                <span>ลบห้องเรียน</span>
              </button>
            )}
          </div>
        )}
      </div>

      {/* Course Hero Banner */}
      <div className="relative overflow-hidden rounded-3xl border border-emerald-400/25 dark:border-emerald-800/45 theme-hero-surface text-white shadow-xl theme-transition">
        {safeCover ? (
          <img
            src={safeCover}
            alt={classroom.title}
            referrerPolicy="no-referrer"
            className="absolute inset-0 w-full h-full object-cover"
          />
        ) : (
          <div className="absolute inset-0 theme-hero-surface" />
        )}
        <div className="absolute inset-0 theme-hero-scrim" />
        <div className="absolute inset-0 edu-hero-grid opacity-30 pointer-events-none" />
        <HeroSvgOrnaments variant="classroom" />

        <div className="relative z-10 p-6 sm:p-8 flex flex-col lg:flex-row lg:items-end justify-between gap-6">
          <div className="space-y-3 max-w-3xl">
            <div className="flex flex-wrap items-center gap-2 text-xs text-emerald-200 font-semibold">
              <span className="font-mono text-white bg-emerald-700/85 px-2.5 py-0.5 rounded-md">
                {classroom.courseCode}
              </span>
              <span aria-hidden="true">·</span>
              <span>{classroom.subject}</span>
              <span aria-hidden="true">·</span>
              <span>ระดับชั้น {classroom.gradeLevel}</span>
              {classroom.isPublished === false && (
                <>
                  <span aria-hidden="true">·</span>
                  <span className="text-amber-300">ฉบับร่าง (ซ่อนจากนักเรียน)</span>
                </>
              )}
            </div>

            <h1 className="text-2xl sm:text-3xl font-bold font-prompt tracking-tight leading-snug text-balance">
              {classroom.title}
            </h1>

            {classroom.description && (
              <p className="text-xs sm:text-sm text-slate-200/95 leading-relaxed max-w-2xl">
                {classroom.description}
              </p>
            )}

            <div className="pt-1 flex flex-wrap items-center gap-4 text-xs text-slate-300">
              <span className="inline-flex items-center gap-1.5">
                <User className="w-3.5 h-3.5 text-emerald-300" />
                <span>ครูผู้สอน: {classroom.teacherName}</span>
              </span>
              <span className="inline-flex items-center gap-1.5">
                <Layers className="w-3.5 h-3.5 text-emerald-300" />
                <span className="tabular-nums">{sortedUnits.length} หน่วยการเรียนรู้</span>
              </span>
              <span className="inline-flex items-center gap-1.5">
                <Users className="w-3.5 h-3.5 text-emerald-300" />
                <span className="tabular-nums">{roomStudents.length} นักเรียนในห้อง</span>
              </span>
            </div>
          </div>

          {/* Student Progress or Summary Card */}
          <div className="bg-white/10 backdrop-blur-md border border-white/15 rounded-2xl p-4 sm:min-w-[230px] shrink-0 space-y-2">
            <div className="flex items-center justify-between text-xs">
              <span className="text-slate-200 font-medium">
                {role === 'student' ? 'ความคืบหน้าการส่งงาน' : 'ภาพรวมใบงานในวิชา'}
              </span>
              <span className="font-mono font-bold text-white tabular-nums">
                {role === 'student'
                  ? `${studentProgress.pct}%`
                  : `${subjectAssignments.length} ใบงาน`}
              </span>
            </div>
            {role === 'student' ? (
              <>
                <div className="h-2 bg-white/15 rounded-full overflow-hidden">
                  <div
                    className="h-full bg-emerald-400 rounded-full transition-all duration-300"
                    style={{ width: `${studentProgress.pct}%` }}
                  />
                </div>
                <p className="text-[11px] text-slate-200 tabular-nums">
                  ส่งแล้ว {studentProgress.completed} จาก {studentProgress.total} รายการ
                </p>
              </>
            ) : (
              <p className="text-[11px] text-slate-200">
                เชื่อมสื่อและใบงานอัตโนมัติตามรายวิชา {classroom.subject}
              </p>
            )}
          </div>
        </div>
      </div>

      {/* Course Objectives Callout (if specified) */}
      {classroom.objectives && (
        <div className="relative overflow-hidden bg-white dark:bg-[var(--theme-surface-dark)] border border-emerald-200/75 dark:border-emerald-950/70 rounded-2xl p-5 flex items-start gap-3 theme-transition">
          <CardCornerOrnament className="absolute -top-3 -right-3 w-24 h-24 opacity-55" />
          <div className="p-2 bg-emerald-50 dark:bg-emerald-950/60 text-emerald-700 dark:text-emerald-400 rounded-xl shrink-0">
            <Target className="w-5 h-5" />
          </div>
          <div className="space-y-1 relative z-10">
            <h2 className="text-sm font-bold font-prompt text-slate-900 dark:text-white">
              จุดประสงค์ / ผลการเรียนรู้ประจำรายวิชา
            </h2>
            <p className="text-xs text-slate-600 dark:text-slate-300 leading-relaxed whitespace-pre-line">
              {classroom.objectives}
            </p>
          </div>
        </div>
      )}

      {/* Inner Segmented Navigation Tabs */}
      <div className="flex flex-wrap items-center gap-1.5 p-1.5 theme-soft-surface dark:bg-emerald-950/30 border border-emerald-100/80 dark:border-emerald-950/60 rounded-2xl theme-transition">
        <button
          type="button"
          onClick={() => setInnerTab('units')}
          className={`flex-1 sm:flex-initial px-4 py-2 rounded-xl text-xs font-bold transition-colors inline-flex items-center justify-center gap-2 cursor-pointer whitespace-nowrap ${
            innerTab === 'units'
              ? 'bg-white dark:bg-[var(--theme-surface-dark)] text-emerald-700 dark:text-emerald-400 shadow-xs'
              : 'text-slate-600 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white'
          }`}
        >
          <Layers className="w-4 h-4" />
          <span>บทเรียนและหน่วยการเรียนรู้ ({sortedUnits.length})</span>
        </button>

        <button
          type="button"
          onClick={() => setInnerTab('worksheets')}
          className={`flex-1 sm:flex-initial px-4 py-2 rounded-xl text-xs font-bold transition-colors inline-flex items-center justify-center gap-2 cursor-pointer whitespace-nowrap ${
            innerTab === 'worksheets'
              ? 'bg-white dark:bg-[var(--theme-surface-dark)] text-emerald-700 dark:text-emerald-400 shadow-xs'
              : 'text-slate-600 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white'
          }`}
        >
          <FileText className="w-4 h-4" />
          <span>ใบงานในรายวิชา ({subjectAssignments.length})</span>
        </button>

        <button
          type="button"
          onClick={() => setInnerTab('members')}
          className={`flex-1 sm:flex-initial px-4 py-2 rounded-xl text-xs font-bold transition-colors inline-flex items-center justify-center gap-2 cursor-pointer whitespace-nowrap ${
            innerTab === 'members'
              ? 'bg-white dark:bg-[var(--theme-surface-dark)] text-emerald-700 dark:text-emerald-400 shadow-xs'
              : 'text-slate-600 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white'
          }`}
        >
          <Users className="w-4 h-4" />
          <span>สื่อและรายชื่อนักเรียน ({subjectResources.length} / {roomStudents.length})</span>
        </button>
      </div>

      {/* TAB 1: Course Units & Syllabus Modules */}
      {innerTab === 'units' && (
        <div className="space-y-4">
          {sortedUnits.map((unit, idx) => {
            const isOpen = Boolean(expandedUnitIds[unit.id]);
            const safeMediaUrl = sanitizeHttpUrl(unit.mediaUrl);
            const ytEmbed = safeMediaUrl ? getYouTubeEmbedUrl(safeMediaUrl) : null;
            const unitAssignments = assignments.filter((a) =>
              (unit.linkedAssignmentIds || []).includes(a.id)
            );
            const unitResources = resources.filter((r) =>
              (unit.linkedResourceIds || []).includes(r.id)
            );

            return (
              <div
                key={unit.id}
                className="bg-white dark:bg-[var(--theme-surface-dark)] border border-slate-200/80 dark:border-emerald-950/70 rounded-2xl overflow-hidden shadow-xs"
              >
                <button
                  type="button"
                  onClick={() => toggleUnit(unit.id)}
                  className="w-full px-5 py-4 flex items-center justify-between gap-4 text-left hover:bg-emerald-50/50 dark:hover:bg-emerald-950/30 transition-colors cursor-pointer"
                >
                  <div className="flex items-center gap-3.5 min-w-0">
                    <div className="w-9 h-9 rounded-xl bg-emerald-50 dark:bg-emerald-950/70 border border-emerald-100 dark:border-emerald-900 text-emerald-800 dark:text-emerald-300 font-mono text-sm font-bold flex items-center justify-center shrink-0 tabular-nums">
                      {String(idx + 1).padStart(2, '0')}
                    </div>
                    <div className="min-w-0">
                      <h3 className="text-sm sm:text-base font-bold font-prompt text-slate-900 dark:text-white truncate">
                        {unit.title}
                      </h3>
                      <p className="text-[11px] text-slate-500 dark:text-slate-400">
                        {unitAssignments.length} ใบงาน · {unitResources.length} สื่อประกอบ
                        {safeMediaUrl ? ' · มีสื่อบทเรียนออนไลน์' : ''}
                      </p>
                    </div>
                  </div>
                  {isOpen ? (
                    <ChevronUp className="w-5 h-5 text-slate-400 shrink-0" />
                  ) : (
                    <ChevronDown className="w-5 h-5 text-slate-400 shrink-0" />
                  )}
                </button>

                {isOpen && (
                  <div className="px-5 pb-5 pt-2 border-t border-slate-100 dark:border-slate-800 space-y-4">
                    {unit.description && (
                      <p className="text-xs sm:text-sm text-slate-600 dark:text-slate-300 leading-relaxed whitespace-pre-line">
                        {unit.description}
                      </p>
                    )}

                    {/* Direct Unit Media */}
                    {safeMediaUrl && (
                      <div className="p-3.5 rounded-xl theme-soft-surface dark:bg-slate-800/60 border border-slate-200 dark:border-slate-700 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
                        <div className="flex items-center gap-3 min-w-0">
                          <div className="w-9 h-9 rounded-xl bg-emerald-700 text-white flex items-center justify-center shrink-0">
                            {unit.mediaType === 'video' ? (
                              <Video className="w-4 h-4" />
                            ) : (
                              <BookOpen className="w-4 h-4" />
                            )}
                          </div>
                          <div className="min-w-0">
                            <p className="text-xs font-bold text-slate-900 dark:text-white truncate">
                              {unit.mediaTitle || unit.title}
                            </p>
                            <p className="text-[11px] text-slate-500 dark:text-slate-400 truncate">
                              สื่อบทเรียนประกอบหน่วยการเรียนรู้
                            </p>
                          </div>
                        </div>

                        {ytEmbed ? (
                          <button
                            type="button"
                            onClick={() =>
                              setActiveVideo({
                                url: ytEmbed,
                                title: unit.mediaTitle || unit.title,
                              })
                            }
                            className="px-4 py-2 bg-emerald-700 hover:bg-emerald-800 text-white rounded-xl text-xs font-bold inline-flex items-center justify-center gap-1.5 cursor-pointer shrink-0"
                          >
                            <Play className="w-3.5 h-3.5" />
                            <span>เปิดดูวิดีโอ</span>
                          </button>
                        ) : (
                          <a
                            href={safeMediaUrl}
                            target="_blank"
                            rel="noopener noreferrer"
                            className="px-4 py-2 bg-emerald-700 hover:bg-emerald-800 text-white rounded-xl text-xs font-bold inline-flex items-center justify-center gap-1.5 shrink-0"
                          >
                            <ExternalLink className="w-3.5 h-3.5" />
                            <span>เปิดดูบทเรียน</span>
                          </a>
                        )}
                      </div>
                    )}

                    {/* Linked Resources */}
                    {unitResources.length > 0 && (
                      <div className="space-y-2">
                        <h4 className="text-xs font-bold text-slate-700 dark:text-slate-300 flex items-center gap-1.5">
                          <FolderOpen className="w-3.5 h-3.5 text-emerald-600 dark:text-emerald-400" />
                          <span>สื่อการเรียนรู้จากคลังสื่อ</span>
                        </h4>
                        <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
                          {unitResources.map((res) => {
                            const resUrl = sanitizeHttpUrl(res.url);
                            const resYt = resUrl ? getYouTubeEmbedUrl(resUrl) : null;
                            return (
                              <div
                                key={res.id}
                                className="p-3 rounded-xl border border-slate-200 dark:border-emerald-950/60 bg-white dark:bg-[var(--theme-surface-dark-elevated)]/70 flex items-center justify-between gap-3"
                              >
                                <div className="min-w-0">
                                  <p className="text-xs font-semibold text-slate-900 dark:text-white truncate">
                                    {res.title}
                                  </p>
                                  <p className="text-[11px] text-slate-400">
                                    {res.subject} · {res.gradeLevel}
                                  </p>
                                </div>
                                {resUrl &&
                                  (resYt ? (
                                    <button
                                      type="button"
                                      onClick={() => setActiveVideo({ url: resYt, title: res.title })}
                                      className="px-3 py-1.5 bg-emerald-50 dark:bg-emerald-950/60 text-emerald-700 dark:text-emerald-300 hover:bg-emerald-100 rounded-lg text-[11px] font-bold shrink-0 cursor-pointer"
                                    >
                                      ดูวิดีโอ
                                    </button>
                                  ) : (
                                    <a
                                      href={resUrl}
                                      target="_blank"
                                      rel="noopener noreferrer"
                                      className="px-3 py-1.5 bg-emerald-50 dark:bg-emerald-950/60 text-emerald-700 dark:text-emerald-300 hover:bg-emerald-100 rounded-lg text-[11px] font-bold shrink-0"
                                    >
                                      เปิดสื่อ
                                    </a>
                                  ))}
                              </div>
                            );
                          })}
                        </div>
                      </div>
                    )}

                    {/* Linked Assignments */}
                    {unitAssignments.length > 0 && (
                      <div className="space-y-2">
                        <h4 className="text-xs font-bold text-slate-700 dark:text-slate-300 flex items-center gap-1.5">
                          <FileText className="w-3.5 h-3.5 text-emerald-600 dark:text-emerald-400" />
                          <span>ใบงานและแบบฝึกหัดประจำหน่วย</span>
                        </h4>
                        <div className="space-y-2">
                          {unitAssignments.map((asg) => {
                            const mySub = submissions.find(
                              (s) =>
                                s.assignmentId === asg.id &&
                                (!currentStudentCode || s.studentCode === currentStudentCode)
                            );
                            const totalSubCount = submissions.filter(
                              (s) => s.assignmentId === asg.id && s.status !== 'pending'
                            ).length;
                            const isGroup = asg.workMode === 'group';

                            return (
                              <div
                                key={asg.id}
                                className="p-3.5 rounded-xl border border-slate-200 dark:border-emerald-950/60 bg-white dark:bg-[var(--theme-surface-dark-elevated)]/70 flex flex-col sm:flex-row sm:items-center justify-between gap-3"
                              >
                                <div className="min-w-0 space-y-0.5">
                                  <p className="text-xs sm:text-sm font-bold text-slate-900 dark:text-white truncate">
                                    {asg.title}
                                  </p>
                                  <div className="flex flex-wrap items-center gap-2 text-[11px] text-slate-500 dark:text-slate-400">
                                    <span>{asg.gradeLevel}</span>
                                    <span aria-hidden="true">·</span>
                                    <span className="tabular-nums">{asg.totalPoints} คะแนน</span>
                                    {isGroup && (
                                      <>
                                        <span aria-hidden="true">·</span>
                                        <span className="font-semibold text-teal-700 dark:text-teal-400">
                                          งานกลุ่ม (สูงสุด {asg.groupSettings?.maxGroupSize ?? 4} คน)
                                        </span>
                                      </>
                                    )}
                                    <span aria-hidden="true">·</span>
                                    <span>
                                      กำหนดส่ง {new Date(asg.dueDate).toLocaleDateString('th-TH')}
                                    </span>
                                    {role === 'student' && mySub && (
                                      <>
                                        <span aria-hidden="true">·</span>
                                        <span
                                          className={`inline-flex items-center gap-1 font-semibold ${
                                            mySub.status === 'graded'
                                              ? 'text-emerald-600 dark:text-emerald-400'
                                              : mySub.status === 'pending'
                                              ? 'text-teal-700 dark:text-teal-400'
                                              : mySub.status === 'needs_revision'
                                              ? 'text-rose-600 dark:text-rose-400'
                                              : 'text-amber-700 dark:text-amber-400'
                                          }`}
                                        >
                                          <CheckCircle2 className="w-3 h-3" />
                                          {mySub.status === 'graded'
                                            ? `ตรวจแล้ว (${mySub.score ?? 0}/${asg.totalPoints})`
                                            : mySub.status === 'pending'
                                            ? isGroup
                                              ? 'ร่างงานกลุ่ม'
                                              : 'กำลังทำร่าง'
                                            : mySub.status === 'needs_revision'
                                            ? 'ให้กลับไปแก้ไข'
                                            : 'ส่งงานแล้ว (รอตรวจ)'}
                                        </span>
                                      </>
                                    )}
                                    {role === 'student' && !mySub && (
                                      <>
                                        <span aria-hidden="true">·</span>
                                        <span className="inline-flex items-center gap-1 text-amber-600 dark:text-amber-400 font-semibold">
                                          <Clock className="w-3 h-3" />
                                          ยังไม่ส่ง
                                        </span>
                                      </>
                                    )}
                                  </div>
                                </div>

                                {role === 'student' ? (
                                  <button
                                    type="button"
                                    onClick={() => onOpenSubmitModal(asg)}
                                    className="px-4 py-2 bg-emerald-700 hover:bg-emerald-800 text-white rounded-xl text-xs font-bold shrink-0 cursor-pointer transition-colors"
                                  >
                                    {!mySub || mySub.status === 'pending'
                                      ? isGroup
                                        ? mySub
                                          ? 'ทำใบงานกลุ่มต่อ'
                                          : 'เข้ากลุ่ม / ทำใบงาน'
                                        : mySub
                                        ? 'ทำใบงานต่อ'
                                        : 'ทำใบงาน'
                                      : 'ดูใบงาน / แก้ไขคำตอบ'}
                                  </button>
                                ) : (
                                  <button
                                    type="button"
                                    onClick={() =>
                                      onOpenRosterModal
                                        ? onOpenRosterModal(asg)
                                        : onOpenGradingModal(asg)
                                    }
                                    className="px-4 py-2 bg-emerald-50 dark:bg-emerald-950/60 hover:bg-emerald-100 text-emerald-800 dark:text-emerald-300 rounded-xl text-xs font-bold shrink-0 cursor-pointer tabular-nums transition-colors"
                                  >
                                    ตรวจงาน ({totalSubCount} คน)
                                  </button>
                                )}
                              </div>
                            );
                          })}
                        </div>
                      </div>
                    )}

                    {!unit.description &&
                      !safeMediaUrl &&
                      unitResources.length === 0 &&
                      unitAssignments.length === 0 && (
                        <p className="text-xs text-slate-400">
                          ยังไม่มีรายละเอียดหรือกิจกรรมในหน่วยการเรียนรู้นี้
                        </p>
                      )}
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}

      {/* TAB 2: All Subject Worksheets */}
      {innerTab === 'worksheets' && (
        <div className="space-y-4">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 bg-white dark:bg-[var(--theme-surface-dark)] px-5 py-4 rounded-2xl border border-emerald-100/80 dark:border-emerald-950/70 shadow-2xs theme-transition">
            <div>
              <h3 className="text-sm sm:text-base font-bold font-prompt text-slate-900 dark:text-white flex items-center gap-2">
                <FileText className="w-4 h-4 text-emerald-700 dark:text-emerald-400" />
                <span>ใบงานในรายวิชา {classroom.subject}</span>
              </h3>
              <p className="text-xs text-slate-500 dark:text-slate-400 mt-0.5">
                ระดับชั้น {classroom.gradeLevel} · {subjectAssignments.length} รายการ
              </p>
            </div>

            {role === 'teacher' && onOpenCreateWorksheet && (
              <button
                type="button"
                onClick={() =>
                  onOpenCreateWorksheet({
                    subject: classroom.subject,
                    gradeLevel: classroom.gradeLevel,
                  })
                }
                className="theme-btn-sheen px-4 py-2.5 bg-emerald-700 hover:bg-emerald-800 text-white rounded-xl text-xs font-bold shadow-sm transition-all inline-flex items-center justify-center gap-1.5 cursor-pointer shrink-0"
              >
                <FilePlus className="w-4 h-4" />
                <span>สร้างใบงานในวิชานี้</span>
              </button>
            )}
          </div>

          {subjectAssignments.length === 0 ? (
            <div className="text-center py-12 px-4 bg-white dark:bg-[var(--theme-surface-dark)] rounded-2xl border border-slate-200 dark:border-emerald-950/60 space-y-3 theme-transition">
              <div className="w-12 h-12 rounded-2xl bg-emerald-50 dark:bg-emerald-950/60 text-emerald-700 dark:text-emerald-400 flex items-center justify-center mx-auto">
                <FileText className="w-6 h-6" />
              </div>
              <p className="text-slate-500 dark:text-slate-400 text-xs">
                ยังไม่มีใบงานในรายวิชา {classroom.subject} ({classroom.gradeLevel})
              </p>
              {role === 'teacher' && onOpenCreateWorksheet && (
                <button
                  type="button"
                  onClick={() =>
                    onOpenCreateWorksheet({
                      subject: classroom.subject,
                      gradeLevel: classroom.gradeLevel,
                    })
                  }
                  className="theme-btn-sheen px-4 py-2 bg-emerald-700 hover:bg-emerald-800 text-white rounded-xl text-xs font-bold shadow-sm transition-all inline-flex items-center gap-1.5 cursor-pointer"
                >
                  <Plus className="w-4 h-4" />
                  <span>สร้างใบงานแรกในวิชานี้</span>
                </button>
              )}
            </div>
          ) : (
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
              {subjectAssignments.map((asg) => {
                const sub = submissions.find(
                  (s) =>
                    s.assignmentId === asg.id &&
                    (!currentStudentCode || s.studentCode === currentStudentCode)
                );
                const subCount = submissions.filter(
                  (s) => s.assignmentId === asg.id && s.status !== 'pending'
                ).length;

                return (
                  <AssignmentCard
                    key={asg.id}
                    assignment={asg}
                    submission={sub}
                    submissionCount={subCount}
                    role={role}
                    currentStudentCode={currentStudentCode}
                    onOpenSubmitModal={onOpenSubmitModal}
                    onOpenGradingModal={onOpenGradingModal}
                    onOpenHintModal={onOpenHintModal}
                    onOpenRosterModal={onOpenRosterModal}
                    onDeleteAssignment={onDeleteAssignment}
                    onEditAssignment={onEditAssignment}
                    onCloneAssignment={onCloneAssignment}
                  />
                );
              })}
            </div>
          )}
        </div>
      )}

      {/* TAB 3: Subject Resources & Classroom Students */}
      {innerTab === 'members' && (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
          <div className="lg:col-span-6 bg-white dark:bg-[var(--theme-surface-dark)] border border-slate-200/80 dark:border-emerald-950/70 rounded-2xl p-5 space-y-3">
            <h3 className="text-sm font-bold font-prompt text-slate-900 dark:text-white flex items-center gap-2">
              <FolderOpen className="w-4 h-4 text-emerald-700 dark:text-emerald-400" />
              <span>สื่อการเรียนรู้ประจำวิชา ({subjectResources.length})</span>
            </h3>

            {subjectResources.length === 0 ? (
              <p className="text-xs text-slate-400 py-6 text-center">
                ยังไม่มีสื่อการเรียนรู้ในวิชา {classroom.subject}
              </p>
            ) : (
              <div className="space-y-2.5">
                {subjectResources.map((res) => {
                  const resUrl = sanitizeHttpUrl(res.url);
                  const resYt = resUrl ? getYouTubeEmbedUrl(resUrl) : null;
                  return (
                    <div
                      key={res.id}
                      className="p-3 rounded-xl border border-slate-200 dark:border-slate-800 flex items-center justify-between gap-3"
                    >
                      <div className="min-w-0">
                        <p className="text-xs font-bold text-slate-900 dark:text-white truncate">
                          {res.title}
                        </p>
                        <p className="text-[11px] text-slate-500 dark:text-slate-400 truncate">
                          {res.gradeLevel} · โดย {res.teacherName}
                        </p>
                      </div>
                      {resUrl &&
                        (resYt ? (
                          <button
                            type="button"
                            onClick={() => setActiveVideo({ url: resYt, title: res.title })}
                            className="px-3 py-1.5 bg-emerald-700 hover:bg-emerald-800 text-white rounded-lg text-[11px] font-bold shrink-0 cursor-pointer"
                          >
                            รับชม
                          </button>
                        ) : (
                          <a
                            href={resUrl}
                            target="_blank"
                            rel="noopener noreferrer"
                            className="px-3 py-1.5 bg-emerald-700 hover:bg-emerald-800 text-white rounded-lg text-[11px] font-bold shrink-0"
                          >
                            เปิดดู
                          </a>
                        ))}
                    </div>
                  );
                })}
              </div>
            )}
          </div>

          <div className="lg:col-span-6 bg-white dark:bg-[var(--theme-surface-dark)] border border-slate-200/80 dark:border-emerald-950/70 rounded-2xl p-5 space-y-3">
            <h3 className="text-sm font-bold font-prompt text-slate-900 dark:text-white flex items-center gap-2">
              <GraduationCap className="w-4 h-4 text-emerald-700 dark:text-emerald-400" />
              <span>นักเรียนในห้องเรียน ({roomStudents.length} คน)</span>
            </h3>

            {roomStudents.length === 0 ? (
              <p className="text-xs text-slate-400 py-6 text-center">
                ยังไม่มีรายชื่อนักเรียนในระดับชั้น {classroom.gradeLevel}
              </p>
            ) : (
              <div className="max-h-96 overflow-y-auto divide-y divide-slate-100 dark:divide-slate-800">
                {roomStudents.map((st, idx) => (
                  <div key={st.id} className="py-2.5 flex items-center justify-between gap-3 text-xs">
                    <div className="flex items-center gap-2.5 min-w-0">
                      <span className="w-6 text-center font-mono text-[11px] text-slate-400 tabular-nums shrink-0">
                        {idx + 1}
                      </span>
                      <span className="font-mono text-[11px] text-emerald-700 dark:text-emerald-400 font-semibold shrink-0">
                        {st.code}
                      </span>
                      <span className="font-medium text-slate-800 dark:text-slate-200 truncate">
                        {st.name}
                      </span>
                    </div>
                    <span className="text-[11px] text-slate-500 dark:text-slate-400 shrink-0">
                      {st.gradeLevel}
                    </span>
                  </div>
                ))}
              </div>
            )}
          </div>
        </div>
      )}

      {/* Video Player Modal */}
      {activeVideo && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-6 bg-slate-950/90 backdrop-blur-md">
          <div className="bg-slate-900 border border-slate-800 rounded-3xl w-full max-w-4xl overflow-hidden shadow-2xl flex flex-col">
            <div className="flex items-center justify-between px-6 py-4 border-b border-slate-800">
              <div className="flex items-center gap-2 truncate pr-4">
                <Video className="w-5 h-5 text-emerald-400 shrink-0" />
                <h3 className="text-sm font-bold font-prompt text-white truncate">
                  {activeVideo.title}
                </h3>
              </div>
              <button
                type="button"
                onClick={() => setActiveVideo(null)}
                className="p-2 text-slate-400 hover:text-white rounded-full hover:bg-slate-800 cursor-pointer"
              >
                <X className="w-5 h-5" />
              </button>
            </div>
            <div className="relative aspect-video bg-black">
              <iframe
                src={activeVideo.url}
                title={activeVideo.title}
                allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture"
                allowFullScreen
                className="w-full h-full border-0"
              />
            </div>
          </div>
        </div>
      )}

      {/* Delete Classroom Confirmation Modal */}
      {confirmDeleteOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-xs">
          <div className="bg-white dark:bg-[var(--theme-surface-dark)] border border-slate-200 dark:border-emerald-950/60 rounded-2xl w-full max-w-sm shadow-2xl p-6 text-center space-y-4">
            <div className="w-12 h-12 rounded-2xl bg-rose-100 dark:bg-rose-950/60 text-rose-600 dark:text-rose-400 flex items-center justify-center mx-auto">
              <Trash2 className="w-6 h-6" />
            </div>
            <div>
              <h3 className="text-base font-bold font-prompt text-slate-900 dark:text-white">
                ยืนยันการลบห้องเรียนรายวิชา?
              </h3>
              <p className="text-xs text-slate-500 dark:text-slate-400 mt-1.5 leading-relaxed">
                ห้องเรียน <strong>"{classroom.courseCode} · {classroom.title}"</strong> จะถูกลบออก (ใบงานและสื่อการเรียนรู้เดิมในระบบจะไม่ถูกลบ)
              </p>
            </div>
            <div className="flex gap-2.5 pt-2">
              <button
                type="button"
                onClick={() => setConfirmDeleteOpen(false)}
                className="flex-1 py-2.5 px-4 bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 text-slate-700 dark:text-slate-300 rounded-xl text-xs font-semibold cursor-pointer"
              >
                ยกเลิก
              </button>
              <button
                type="button"
                onClick={() => {
                  setConfirmDeleteOpen(false);
                  onDeleteClassroom(classroom.id);
                }}
                className="flex-1 py-2.5 px-4 bg-rose-600 hover:bg-rose-700 text-white rounded-xl text-xs font-bold cursor-pointer"
              >
                ยืนยันลบ
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
